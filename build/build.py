import os
import base64
import re

def strip_exports_and_imports(code):
    code = re.sub(r'import\s+[^;]+;', '', code)
    code = re.sub(r'export\s+(async\s+)?(function|const|let|var)\s+', r'\1\2 ', code)
    code = re.sub(r'export\s+default\s+', '', code)
    code = re.sub(r'export\s*\{[^}]*\};?', '', code)
    return code

def build_single_file():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.abspath(os.path.join(base_dir, '..'))
    src_dir = os.path.join(project_dir, 'src')
    dist_file = os.path.join(project_dir, 'hompage_test.html')

    print(f"Building single-file HTML bundle from {src_dir} -> {dist_file}")

    # 1. Read Base64 logo
    logo_path = os.path.join(project_dir, 'tagsci logo.png')
    with open(logo_path, 'rb') as f:
        logo_b64 = base64.b64encode(f.read()).decode('utf-8')

    # 2. Read modular source files
    with open(os.path.join(src_dir, 'data', 'study_data.js'), 'r', encoding='utf-8') as f:
        study_data_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'math_engine.js'), 'r', encoding='utf-8') as f:
        math_engine_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'calendar.js'), 'r', encoding='utf-8') as f:
        calendar_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'reviewers.js'), 'r', encoding='utf-8') as f:
        reviewers_js = strip_exports_and_imports(f.read())
        reviewers_js = reviewers_js.replace('window.App.openReviewer', 'openReviewer')

    with open(os.path.join(src_dir, 'components', 'tasks.js'), 'r', encoding='utf-8') as f:
        tasks_js = strip_exports_and_imports(f.read())
        tasks_js = tasks_js.replace('window.App.toggleTask', 'toggleTask')
        tasks_js = tasks_js.replace('window.App.deleteTask', 'deleteTask')

    with open(os.path.join(src_dir, 'components', 'quiz_engine.js'), 'r', encoding='utf-8') as f:
        quiz_engine_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'navigation.js'), 'r', encoding='utf-8') as f:
        navigation_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'ota_sync.js'), 'r', encoding='utf-8') as f:
        ota_sync_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'components', 'pwa_installer.js'), 'r', encoding='utf-8') as f:
        pwa_installer_js = strip_exports_and_imports(f.read())

    with open(os.path.join(src_dir, 'app.js'), 'r', encoding='utf-8') as f:
        app_js = strip_exports_and_imports(f.read())

    bundled_js = f"""
    /* =========================================================
       BUNDLED LOCAL DATA & MODULES (Generated by build.py)
       ========================================================= */
    {study_data_js}

    {math_engine_js}

    {calendar_js}

    {reviewers_js}

    {tasks_js}

    {quiz_engine_js}

    {navigation_js}

    {ota_sync_js}

    {pwa_installer_js}

    {app_js}
    """

    # 3. Read template HTML from src/index.html
    with open(os.path.join(src_dir, 'index.html'), 'r', encoding='utf-8') as f:
        html = f.read()

    # Replace logo relative path with data URI
    html = html.replace('src="../tagsci logo.png"', f'src="data:image/png;base64,{logo_b64}"')

    # Safe replace module script tag using literal string replacement
    target_script = '<script type="module" src="./app.js"></script>'
    if target_script in html:
        html = html.replace(target_script, f'<script>{bundled_js}</script>')
    else:
        html = re.sub(r'<script\s+type="module"\s+src="./app.js"></script>', lambda m: f'<script>{bundled_js}</script>', html)

    # Clean window.App calls to direct calls in HTML for single file
    html = html.replace('window.App.', '')

    # Write both hompage_test.html and production root index.html for GitHub Pages
    with open(dist_file, 'w', encoding='utf-8') as f:
        f.write(html)

    github_pages_index = os.path.join(project_dir, 'index.html')
    with open(github_pages_index, 'w', encoding='utf-8') as f:
        f.write(html)

    # 4. Synchronize Service Worker and Web Manifest to root for GitHub Pages
    src_sw = os.path.join(src_dir, 'service-worker.js')
    root_sw = os.path.join(project_dir, 'service-worker.js')
    if os.path.exists(src_sw):
        with open(src_sw, 'r', encoding='utf-8') as f_in, open(root_sw, 'w', encoding='utf-8') as f_out:
            f_out.write(f_in.read())

    src_manifest = os.path.join(src_dir, 'manifest.json')
    root_manifest = os.path.join(project_dir, 'manifest.json')
    if os.path.exists(src_manifest):
        with open(src_manifest, 'r', encoding='utf-8') as f_in, open(root_manifest, 'w', encoding='utf-8') as f_out:
            f_out.write(f_in.read())

    print("Successfully built standalone index.html (GitHub Pages) and hompage_test.html with embedded quiz engine & PWA support!")

if __name__ == '__main__':
    build_single_file()
